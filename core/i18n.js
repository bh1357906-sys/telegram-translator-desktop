  function T(s) {
    let out = current === 'en' && Object.prototype.hasOwnProperty.call(EN, s) ? EN[s] : s;
    for (let i = 1; i < arguments.length; i++) out = String(out).split('{' + (i - 1) + '}').join(arguments[i]);
    return out;
  }

  // 翻译页面上的静态文字：文本节点、placeholder、title。记住原文，切回中文时能还原。
  const ORIG = typeof WeakMap !== 'undefined' ? new WeakMap() : null;
  function localizeText(orig) {
    const t = orig.trim();
    if (!t || current !== 'en' || !Object.prototype.hasOwnProperty.call(EN, t)) return orig;
    const lead = orig.slice(0, orig.indexOf(t));
    const tail = orig.slice(orig.indexOf(t) + t.length);
    return lead + EN[t] + tail;
  }
  function localizeDom(rootEl) {
    if (!rootEl || !ORIG || typeof document === 'undefined') return;
    const walker = document.createTreeWalker(rootEl, 1 | 4); // 元素 + 文本
    let n = rootEl;
    while (n) {
      if (n.nodeType === 3) {
        const p = n.parentNode && n.parentNode.nodeName;
        if (p !== 'SCRIPT' && p !== 'STYLE') {
          if (!ORIG.has(n)) ORIG.set(n, { text: n.nodeValue });
          const o = ORIG.get(n);
          // 页面脚本改过的文字（不是我们上次翻译的结果）以新文字为准
          if (o.last !== undefined && n.nodeValue !== o.last) o.text = n.nodeValue;
          o.last = localizeText(o.text);
          if (n.nodeValue !== o.last) n.nodeValue = o.last;
        }
      } else if (n.nodeType === 1) {
        for (const attr of ['placeholder', 'title', 'aria-label']) {
          if (!n.hasAttribute(attr)) continue;
          const key = 'attr:' + attr;
          let o = ORIG.get(n);
          if (!o) ORIG.set(n, (o = {}));
          if (o[key + ':last'] !== undefined && n.getAttribute(attr) !== o[key + ':last']) o[key] = n.getAttribute(attr);
          if (o[key] === undefined) o[key] = n.getAttribute(attr);
          o[key + ':last'] = localizeText(o[key]);
          n.setAttribute(attr, o[key + ':last']);
        }
      }
      n = walker.nextNode();
    }
    if (rootEl === document.body || rootEl === document.documentElement) document.documentElement.lang = current === 'en' ? 'en' : 'zh-CN';
  }

  return { T, setLang, getLang, localizeDom, EN };
